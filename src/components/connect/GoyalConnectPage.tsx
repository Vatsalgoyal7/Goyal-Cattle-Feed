// ─── WhatsApp Tab ─────────────────────────────────────────────────────────────
const WhatsAppTab: React.FC = () => {
  const { invoices, customers } = useEnterprise();
  const [toast, setToast] = useState('');
  const showToast = (m: string) => { setToast(m); setTimeout(() => setToast(''), 3000); };

  const recentInvoices = invoices.slice(0, 5);
  const topOutstanding = [...customers].sort((a, b) => b.currentOutstanding - a.currentOutstanding).slice(0, 3);

  const shareInvoice = (inv: typeof invoices[0]) => {
    const phone = customers.find(c => c.id === inv.customerId)?.mobile?.replace(/[^0-9]/g, '') || '';
    const text = encodeURIComponent(
      `Dear ${inv.customerFirm || inv.customerName},\n\nYour invoice ${inv.invoiceNumber} dated ${inv.invoiceDate} of ₹${inv.grandTotal.toLocaleString('en-IN')} is ready.\n\nPayment Status: ${inv.paymentStatus}\nDue: ${inv.dueDate}\n\n– Goyal Cattle Feed Pvt. Ltd.`
    );
    if (phone) window.open(`https://wa.me/91${phone}?text=${text}`, '_blank');
    else window.open(`https://wa.me/?text=${text}`, '_blank');
  };

  const sendReminder = (c: typeof customers[0]) => {
    const phone = c.mobile?.replace(/[^0-9]/g, '') || '';
    const text = encodeURIComponent(
      `Dear ${c.firmName},\n\nThis is a gentle reminder that ₹${c.currentOutstanding.toLocaleString('en-IN')} is outstanding in your account.\n\nKindly arrange payment at your earliest convenience.\n\n– Goyal Cattle Feed Pvt. Ltd.\n📞 Contact: +91 161 2XXXXXX`
    );
    if (phone) window.open(`https://wa.me/91${phone}?text=${text}`, '_blank');
    else window.open(`https://wa.me/?text=${text}`, '_blank');
  };

  const totalSalesToday = invoices
    .filter(i => i.invoiceDate === new Date().toLocaleDateString('en-GB'))
    .reduce((s, i) => s + i.grandTotal, 0);

  const shareReport = () => {
    const text = encodeURIComponent(
      `📊 Goyal Cattle Feed – Daily Report\n📅 ${new Date().toLocaleDateString('en-IN')}\n\n💰 Today's Sales: ₹${totalSalesToday.toLocaleString('en-IN')}\n📦 Invoices Raised: ${invoices.filter(i => i.invoiceDate === new Date().toLocaleDateString('en-GB')).length}\n\nReport generated by Goyal Business OS`
    );
    window.open(`https://wa.me/?text=${text}`, '_blank');
  };

  return (
    <div className="space-y-5">
      {toast && <div className="fixed top-20 right-4 z-50 bg-green-700 text-white px-4 py-2 rounded-xl text-xs shadow-lg">{toast}</div>}

      <div className="flex items-start gap-2 p-3 rounded-xl bg-green-50 dark:bg-green-950/40 border border-green-200 dark:border-green-800 text-xs">
        <Info className="w-4 h-4 text-green-700 shrink-0 mt-0.5" />
        <span className="text-green-800 dark:text-green-200">Manual WhatsApp Sharing via wa.me links. No WhatsApp Business API configured \u2013 no automated sending.</span>
      </div>

      {/* Recent Invoices */}
      <div className="space-y-2">
        <h3 className="text-xs font-bold text-slate-700 dark:text-slate-300 uppercase">Share Invoices</h3>
        {recentInvoices.map(inv => (
          <div key={inv.id} className="flex items-center justify-between p-3 rounded-xl border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800 text-xs">
            <div>
              <p className="font-semibold text-slate-800 dark:text-slate-200">{inv.invoiceNumber}</p>
              <p className="text-slate-500">{inv.customerFirm || inv.customerName} · ₹{inv.grandTotal.toLocaleString('en-IN')}</p>
            </div>
            <button onClick={() => shareInvoice(inv)} className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-green-600 hover:bg-green-700 text-white font-semibold transition-colors">
              <Share2 className="w-3 h-3" /> WhatsApp
            </button>
          </div>
        ))}
      </div>

      {/* Payment Reminders */}
      <div className="space-y-2">
        <h3 className="text-xs font-bold text-slate-700 dark:text-slate-300 uppercase">Payment Reminders</h3>
        {topOutstanding.map(c => (
          <div key={c.id} className="flex items-center justify-between p-3 rounded-xl border border-amber-200 dark:border-amber-800 bg-amber-50 dark:bg-amber-950/30 text-xs">
            <div>
              <p className="font-semibold text-slate-800 dark:text-slate-200">{c.firmName}</p>
              <p className="text-amber-700 dark:text-amber-400 font-semibold">Outstanding: ₹{c.currentOutstanding.toLocaleString('en-IN')}</p>
            </div>
            <button onClick={() => sendReminder(c)} className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-amber-600 hover:bg-amber-700 text-white font-semibold transition-colors">
              <Send className="w-3 h-3" /> Remind
            </button>
          </div>
        ))}
      </div>

      {/* Daily Report Share */}
      <div className="p-4 rounded-2xl border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800">
        <p className="text-xs font-bold text-slate-700 dark:text-slate-200 mb-2">Share Daily Report</p>
        <div className="flex items-center justify-between">
          <div className="text-xs text-slate-500">Today's Sales: <span className="font-bold text-emerald-700 dark:text-emerald-400">₹{totalSalesToday.toLocaleString('en-IN')}</span></div>
          <button onClick={shareReport} className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-green-600 hover:bg-green-700 text-white text-xs font-semibold transition-colors">
            <Share2 className="w-3 h-3" /> Share Summary
          </button>
        </div>
      </div>
    </div>
  );
};

// ─── Email Tab ────────────────────────────────────────────────────────────────
const EmailTab: React.FC = () => {
  const [host, setHost] = useState(() => localStorage.getItem('goyal_smtp_host') || '');
  const [port, setPort] = useState(() => localStorage.getItem('goyal_smtp_port') || '587');
  const [user, setUser] = useState(() => localStorage.getItem('goyal_smtp_user') || '');
  const [pass, setPass] = useState('');
  const [fromName, setFromName] = useState(() => localStorage.getItem('goyal_smtp_name') || 'Goyal Cattle Feed');
  const [enc, setEnc] = useState('TLS');
  const [showPass, setShowPass] = useState(false);
  const [saved, setSaved] = useState(!!localStorage.getItem('goyal_smtp_host'));
  const [toast, setToast] = useState('');
  const showToast = (m: string) => { setToast(m); setTimeout(() => setToast(''), 3000); };

  const save = () => {
    if (!host || !user) { showToast('Please fill SMTP server and username.'); return; }
    localStorage.setItem('goyal_smtp_host', host);
    localStorage.setItem('goyal_smtp_port', port);
    localStorage.setItem('goyal_smtp_user', user);
    localStorage.setItem('goyal_smtp_name', fromName);
    setSaved(true);
    showToast('SMTP configuration saved locally. Backend mailer required to send emails.');
  };

  return (
    <div className="space-y-4">
      {toast && <div className="fixed top-20 right-4 z-50 bg-indigo-700 text-white px-4 py-2 rounded-xl text-xs shadow-lg">{toast}</div>}
      <div className="flex items-center gap-2 p-3 rounded-xl border border-red-200 dark:border-red-800 bg-red-50 dark:bg-red-950/30 text-xs">
        <AlertTriangle className="w-4 h-4 text-red-600 shrink-0" />
        <span className="text-red-800 dark:text-red-200">SMTP Email is not connected. Configure credentials below. Actual sending requires a server-side mailer (Node.js, PHP, etc.)</span>
      </div>

      <div className="rounded-2xl border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-800 p-4 space-y-3">
        <h3 className="text-xs font-bold text-slate-700 dark:text-slate-200">SMTP Configuration</h3>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
          {[
            { label: 'SMTP Server', val: host, set: setHost, ph: 'smtp.gmail.com' },
            { label: 'Port', val: port, set: setPort, ph: '587' },
            { label: 'Username / Email', val: user, set: setUser, ph: 'your@email.com' },
            { label: 'From Name', val: fromName, set: setFromName, ph: 'Goyal Cattle Feed' },
          ].map(f => (
            <div key={f.label}>
              <label className="text-[11px] font-semibold text-slate-500 uppercase">{f.label}</label>
              <input value={f.val} onChange={e => f.set(e.target.value)} placeholder={f.ph} className="mt-1 w-full px-3 py-2 text-xs rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 focus:outline-none focus:ring-2 focus:ring-indigo-400" />
            </div>
          ))}
          <div>
            <label className="text-[11px] font-semibold text-slate-500 uppercase">Password</label>
            <div className="relative mt-1">
              <input type={showPass ? 'text' : 'password'} value={pass} onChange={e => setPass(e.target.value)} placeholder="App password" className="w-full px-3 py-2 pr-8 text-xs rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 focus:outline-none focus:ring-2 focus:ring-indigo-400" />
              <button onClick={() => setShowPass(!showPass)} className="absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-400"><Eye className="w-3.5 h-3.5" /></button>
            </div>
          </div>
          <div>
            <label className="text-[11px] font-semibold text-slate-500 uppercase">Encryption</label>
            <select value={enc} onChange={e => setEnc(e.target.value)} className="mt-1 w-full px-3 py-2 text-xs rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 focus:outline-none focus:ring-2 focus:ring-indigo-400">
              {['TLS', 'SSL', 'None'].map(o => <option key={o}>{o}</option>)}
            </select>
          </div>
        </div>
        <div className="flex gap-2 pt-1">
          <button onClick={() => showToast('SMTP credentials required to test connection. Backend mailer not configured.')} className="px-4 py-2 rounded-xl border border-slate-300 dark:border-slate-600 text-xs font-semibold text-slate-700 dark:text-slate-300 hover:bg-slate-50 dark:hover:bg-slate-700 transition-colors">Test Connection</button>
          <button onClick={save} className="px-4 py-2 rounded-xl bg-indigo-700 hover:bg-indigo-800 text-white text-xs font-bold transition-colors">Save Configuration</button>
        </div>
        {saved && <p className="text-xs text-emerald-700 dark:text-emerald-400 flex items-center gap-1"><CheckCircle2 className="w-3 h-3" />Configuration saved to local storage.</p>}
      </div>
    </div>
  );
};

